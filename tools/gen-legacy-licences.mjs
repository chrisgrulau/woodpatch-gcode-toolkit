// Generates the licensing records for the third-party libraries upstream
// vendored in legacy/webapp/libs/, from ONE source table:
// tools/data/legacy-libs.json (the licence audit, ADR-0005).
//
//   - REUSE.toml: the block between the BEGIN/END markers.
//   - docs/legacy-libraries.md: a human-readable audit table with evidence.
//
// One table, two outputs, so the machine-readable and human-readable records
// can never disagree.
//
//   node tools/gen-legacy-licences.mjs          rewrite both files
//   node tools/gen-legacy-licences.mjs --check  exit 1 if either is stale (CI)

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const libs = JSON.parse(readFileSync(join(root, 'tools/data/legacy-libs.json'), 'utf8'));
const check = process.argv.includes('--check');

const BEGIN = '# BEGIN legacy-libs (generated by tools/gen-legacy-licences.mjs; do not edit)';
const END = '# END legacy-libs';

const toml = (s) => JSON.stringify(s); // TOML basic strings share JSON's escaping for this data

function reuseBlock() {
  const blocks = libs.map((l) =>
    [
      `# ${l.name} ${l.version}`,
      '[[annotations]]',
      `path = [${l.paths.map(toml).join(', ')}]`,
      'precedence = "override"',
      `SPDX-FileCopyrightText = ${toml(l.copyright)}`,
      `SPDX-License-Identifier = ${toml(l.spdx)}`,
    ].join('\n'),
  );
  return [BEGIN, ...blocks, END].join('\n\n');
}

function auditDoc() {
  const esc = (s) => s.replaceAll('|', '\\|');
  const rows = libs.map(
    (l) =>
      `| ${esc(l.name)} | ${esc(l.version)} | \`${l.spdx}\` | ${l.paths.map((p) => `\`${p.replace('legacy/webapp/libs/', '')}\``).join(', ')} | ${esc(l.evidence)} |`,
  );
  return `<!--
SPDX-FileCopyrightText: 2026 Promotional Notions Pty Ltd trading as Woodpatch House & Garden
SPDX-License-Identifier: MIT
-->

# Licences of upstream's vendored libraries

Generated by \`tools/gen-legacy-licences.mjs\` from \`tools/data/legacy-libs.json\`. Do not edit by hand.

Upstream webgcode vendored these third-party libraries in \`legacy/webapp/libs/\`. They are
redistributed here as received from upstream, each under its own licence, and are
**never built, bundled, published or served** by this project (ADR-0005). The audit that
produced this table was done on 2026-09-25. Where a file carries a licence header, that
header governs; where it doesn't, the licence comes from the library's own project.

| Library | Version | SPDX | Files | Evidence |
| ------- | ------- | ---- | ----- | -------- |
${rows.join('\n')}
`;
}

function spliceReuse(current) {
  const a = current.indexOf(BEGIN);
  const b = current.indexOf(END);
  if (a === -1 || b === -1) throw new Error('REUSE.toml is missing the legacy-libs markers');
  return current.slice(0, a) + reuseBlock() + current.slice(b + END.length);
}

const reusePath = join(root, 'REUSE.toml');
const docPath = join(root, 'docs/legacy-libraries.md');
const outputs = [
  [reusePath, spliceReuse(readFileSync(reusePath, 'utf8'))],
  [docPath, auditDoc()],
];

let stale = false;
for (const [path, want] of outputs) {
  let have = '';
  try {
    have = readFileSync(path, 'utf8');
  } catch {
    // missing file counts as stale
  }
  if (have === want) continue;
  if (check) {
    console.error(`stale: ${path.slice(root.length + 1)} (run node tools/gen-legacy-licences.mjs)`);
    stale = true;
  } else {
    writeFileSync(path, want);
    console.log(`wrote ${path.slice(root.length + 1)}`);
  }
}
process.exit(stale ? 1 : 0);
